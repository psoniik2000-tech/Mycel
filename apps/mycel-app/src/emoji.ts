const KEY = "mycel.recentEmoji";
export function recentEmoji(): string[] {
  try {
    return JSON.parse(localStorage.getItem(KEY) ?? "[]");
  } catch {
    return [];
  }
}
export function useEmoji(e: string) {
  try {
    localStorage.setItem(KEY, JSON.stringify([e, ...recentEmoji().filter((x) => x !== e)].slice(0, 24)));
  } catch {}
}

// One emoji as a capture group for split(): flag, keycap, or a pictograph with modifiers/tags, ZWJ-joined.
export const EMOJI_RE =
  /(\p{Regional_Indicator}{2}|[#*0-9]\uFE0F?\u20E3|\p{Extended_Pictographic}[\uFE0F\p{Emoji_Modifier}\u{E0020}-\u{E007F}]*(?:\u200D\p{Extended_Pictographic}[\uFE0F\p{Emoji_Modifier}]*)*)/gu;
// ©, ®, ™, ‼, ↔ and the like stay text unless written as emoji (FE0F).
export const isArt = (e: string) => e.codePointAt(0)! >= 0x2300 || /[\uFE0F\u20E3]/.test(e);
// Twemoji file name: hex code points, FE0F dropped unless the sequence is ZWJ-joined.
export const emojiFile = (e: string) =>
  [...(e.includes("\u200D") ? e : e.replace(/\uFE0F/g, ""))].map((c) => c.codePointAt(0)!.toString(16)).join("-");
/** How many emoji a message consists of, when it is 1–3 emoji and nothing else; otherwise 0. */
export function emojiOnly(text: string): number {
  const parts = text.split(EMOJI_RE), n = (parts.length - 1) / 2;
  return n <= 3 && parts.every((s, i) => (i % 2 ? isArt(s) : !s.trim())) ? n : 0;
}
